CREATE OR REPLACE FUNCTION pg_temp.expect_rejected_bulk(
  p_source uuid, p_dest uuid, p_year uuid,
  p_motivo text DEFAULT 'Reorganização de turma em teste'
) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  PERFORM public.transferir_turma_em_lote(p_source,p_dest,p_year,p_motivo);
  RAISE EXCEPTION 'UNEXPECTED_BULK_SUCCESS';
EXCEPTION WHEN OTHERS THEN
  IF SQLERRM = 'UNEXPECTED_BULK_SUCCESS' THEN RAISE; END IF;
END $$;
CREATE OR REPLACE FUNCTION pg_temp.expect_direct_guard(p_matricula uuid, p_dest uuid)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  UPDATE public.matriculas SET turma_id=p_dest WHERE id=p_matricula;
  RAISE EXCEPTION 'UNEXPECTED_DIRECT_SUCCESS';
EXCEPTION WHEN OTHERS THEN
  IF SQLERRM = 'UNEXPECTED_DIRECT_SUCCESS' THEN RAISE; END IF;
END $$;

