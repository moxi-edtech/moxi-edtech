CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('app.test_uid', true), '')::uuid
$$;
CREATE TABLE public.escola_users (
  escola_id uuid NOT NULL,
  user_id uuid NOT NULL,
  papel text,
  role text,
  PRIMARY KEY (escola_id, user_id)
);
CREATE FUNCTION public.current_tenant_escola_id() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('app.test_school', true), '')::uuid
$$;
CREATE FUNCTION public.user_has_role_in_school(school uuid, allowed text[]) RETURNS boolean
LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.escola_users e
    WHERE e.escola_id = school AND e.user_id = auth.uid() AND e.papel = ANY(allowed)
  )
$$;

